## Business Questions

1. What are the total sales revenue and total number of orders generated by the business 
  SELECT 
    SUM(Quantity * UnitPrice) AS Total_Revenue,
    COUNT(DISTINCT InvoiceNo) AS Total_Orders
FROM inter1.first;

2. Which products are the best-selling products based on total quantity purchased?
SELECT 
    Description,
    SUM(Quantity) AS Total_Quantity_Sold
FROM inter1.first
GROUP BY Description
ORDER BY Total_Quantity_Sold DESC
LIMIT 10;

3. Which products generate the highest revenue for the company?
SELECT 
    Description,
    SUM(Quantity * UnitPrice) AS Total_Revenue
FROM inter1.first
GROUP BY Description
ORDER BY Total_Revenue DESC
LIMIT 10;

4. Which countries contribute the most to overall sales revenue?
SELECT 
    Country,
    SUM(Quantity * UnitPrice) AS Total_Revenue
FROM inter1.first
GROUP BY Country
ORDER BY Total_Revenue DESC
LIMIT 10;
5. What are the top 10 customers based on their total spending?
SELECT 
    CustomerID,
    SUM(Quantity * UnitPrice) AS Total_Spending
FROM inter1.first
GROUP BY CustomerID
ORDER BY Total_Spending DESC
LIMIT 10
6. How do sales performance and revenue change month by month?
SELECT
    YEAR(InvoiceDate) AS Year,
    MONTH(InvoiceDate) AS Month,
    SUM(Quantity * UnitPrice) AS Monthly_Revenue
FROM inter1.first
GROUP BY 
    YEAR(InvoiceDate),
    MONTH(InvoiceDate)
ORDER BY Year, Month;
7. What are the busiest sales periods based on the number of transactions?
SELECT
    HOUR(InvoiceDate) AS Sales_Hour,
    COUNT(InvoiceNo) AS Number_of_Transactions
FROM inter1.first
GROUP BY HOUR(InvoiceDate)
ORDER BY Number_of_Transactions DESC;

8. Which products have the highest average selling price?
SELECT
    Description,
    AVG(UnitPrice) AS Average_Price
FROM inter1.first
GROUP BY Description
ORDER BY Average_Price DESC
LIMIT 10;

9. What is the average order value, and how does customer purchasing behavior change?
SELECT
    AVG(Order_Total) AS Average_Order_Value
FROM
(
    SELECT
        InvoiceNo,
        SUM(Quantity * UnitPrice) AS Order_Total
    FROM inter1.first
    GROUP BY InvoiceNo
